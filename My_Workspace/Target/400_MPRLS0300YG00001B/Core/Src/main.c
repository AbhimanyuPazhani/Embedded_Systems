/* SENSOR PRESENCE CHECK (closest equivalent to Part ID check)      */
/* ================================================================ */
HAL_StatusTypeDef MPRLS_CheckPresence(void)
{
    uint8_t cmd[3] = CMD_MEASUREMENT;
    uint8_t data[7];
    int success_count = 0;

    for (int i = 0; i < MAX_CHECK_ATTEMPTS; i++)
    {
        // Try to send measurement command
        if (HAL_I2C_Master_Transmit(&hi2c1, MPR_I2C_ADDR, cmd, 3, 100) == HAL_OK)
        {
            HAL_Delay(10);  // conversion time

            if (HAL_I2C_Master_Receive(&hi2c1, MPR_I2C_ADDR, data, 7, 100) == HAL_OK)
            {
                // Check status byte (bit 6 = powered, bit 5 = not busy, memory error = 0)
                if ((data[0] & 0xC0) == 0x40 && (data[0] & 0x04) == 0)
                {
                    success_count++;
                    if (success_count >= 3) return HAL_OK;  // 3 successful reads = reliable
                }
            }
        }
        HAL_Delay(50);
    }
    return HAL_ERROR;
}

/* ================================================================ */
/* PRESSURE READING FUNCTION (Transfer Function B)                 */
/* ================================================================ */
float MPRLS_ReadPressure_mmHg(void)
{
    uint8_t cmd[3] = CMD_MEASUREMENT;
    uint8_t data[7] = {0};

    if (HAL_I2C_Master_Transmit(&hi2c1, MPR_I2C_ADDR, cmd, 3, 100) != HAL_OK)
        return -1.0f;

    HAL_Delay(10);  // typical conversion time

    if (HAL_I2C_Master_Receive(&hi2c1, MPR_I2C_ADDR, data, 7, 100) != HAL_OK)
        return -1.0f;

    // Combine 24-bit pressure counts (MSB first)
    uint32_t press_counts = ((uint32_t)data[1] << 16) |
                            ((uint32_t)data[2] << 8)  |
                             data[3];

    // Apply Transfer Function B for 0-300 mmHg
    float pressure = ((press_counts - OUTPUT_MIN) * (P_MAX - P_MIN)) /
                     (OUTPUT_MAX - OUTPUT_MIN) + P_MIN;

    return pressure;
}
